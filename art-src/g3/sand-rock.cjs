/* G3 沙漠 Boss 场石块：沙岩残柱 / Sandstone Outcrop
 * 3D 像素离线源。不是可采集物，是战场地形：低矮沙岩台、断柱、风蚀孔。
 * 与沙海蜃的玻璃青绿区分：主体暖沙，只在裂缝里透一点冷色。
 */
module.exports = ({ makeBuilder, makeSculpt, KIT: K }) => ({
  id: 'g3-sand-rock', name: '沙岩残柱', seed: 305,
  build(seed) {
    const P = [
      0x050505, 0x0c0b08, 0x15130d, 0x1e1b12, 0x2a2517, 0x39321f,
      0x4a4028, 0x5e5032, 0x776540, 0x917d51, 0xb09a69, 0xd1bb86,
      0xe8d6a7, 0x2a2016, 0x5a3d25,
      0x17534f, 0x2a8177, 0x4cc3a5,
      0x9a6b35, 0xc99348, 0xf1c56b,
    ];
    const B = makeBuilder(seed, P);
    const S = K.sculpt(makeSculpt(B));
    const sandDark = { r: [3, 4] };
    const sandMid = { r: [5, 6] };
    const sandLight = { r: [8, 9] };
    const sandPale = { r: [10, 11] };
    const bone = { r: [11, 12] };
    const glass = { r: [13, 14] };
    const teal = { r: [16, 17] };
    const gold = { r: [18, 19] };
    const dark = { r: [0, 1] };

    // 底座：被沙埋住的低台，给石堆一个“长在地上”的根。
    S.ball([0, 0.28, 0], [0.86, 0.24, 0.62], sandDark, { res: 0.030, rd: 0.08 });
    S.ball([0, 0.36, 0.04], [0.74, 0.12, 0.54], sandMid, { res: 0.022, rd: 0.04 });
    S.box([0, 0.16, 0.22], [1.04, 0.05, 0.46], sandMid, { res: 0.010, rd: 0.02 });

    // 主石堆：三块高低不一致的沙岩，不再做“柱 + 平板”的桌面剪影。
    S.ball([-0.24, 0.62, 0.02], [0.42, 0.50, 0.44], sandMid, { res: 0.025, rd: 0.06 });
    S.ball([0.18, 0.56, 0.00], [0.36, 0.44, 0.40], sandLight, { res: 0.023, rd: 0.05 });
    S.ball([0.00, 0.92, 0.10], [0.30, 0.42, 0.28], sandLight, { res: 0.022, rd: 0.05 });
    S.ball([-0.14, 1.10, 0.06], [0.20, 0.28, 0.19], sandPale, { res: 0.016, rd: 0.03 });

    // 斜插的断片：一块向侧上方翘起的薄岩，打破圆石轮廓。
    S.tube([[0.22, 0.42, 0.14], [0.38, 0.74, 0.12], [0.48, 0.94, 0.08]], 0.10, 0.035, sandPale, { res: 0.014 });

    // 风蚀孔：暗沙口袋，让石堆不是一整块实心。
    S.box([-0.16, 1.00, 0.20], [0.11, 0.09, 0.10], dark, { res: 0.006 });
    S.box([0.20, 0.70, 0.14], [0.08, 0.12, 0.08], dark, { res: 0.005 });

    // 前方塌石：两块低平砂岩，作为散落石。
    S.ball([-0.46, 0.20, 0.34], [0.28, 0.13, 0.22], sandMid, { res: 0.016, rd: 0.04 });
    S.ball([0.40, 0.16, 0.38], [0.22, 0.10, 0.20], sandLight, { res: 0.012, rd: 0.03 });

    // 风蚀裂纹：冷青细线，只透一点，不把石块变成发光物。
    S.tube([[-0.08, 1.06, 0.20], [-0.12, 0.86, 0.22], [-0.02, 0.64, 0.24]], 0.030, 0.008, glass, { res: 0.005 });
    S.box([0.14, 0.82, 0.20], [0.02, 0.14, 0.02], teal, { res: 0.003 });
    S.box([-0.22, 0.70, 0.28], [0.02, 0.10, 0.02], teal, { res: 0.003 });

    // 柱脚沙尘 / 金色沙点：给 1x 一点暖光，不至于整块灰。
    for (const [x, y, z] of [[-0.42, 0.26, 0.42], [0.52, 0.30, 0.30], [0.02, 1.24, 0.12]]) {
      S.ball([x, y, z], [0.035, 0.022, 0.030], gold, { res: 0.004 });
    }

    S.bake();
    return B.finish({
      cam: { target: [0, 0.64, 0], dist: 5.2, pitch: 0.16, yaw: 0.05 },
      detail: 20, dither: 0.13, radius: 3,
    });
  },
});
